// Builds @pgfsm/api for npm (SPEC-016, #689): one bin, `pgfsm-api`
// (src/cli/index.ts), so `npx @pgfsm/api` runs it. Same shape as
// @pgfsm/async-worker-gateway's build-npm.ts.
//
//   deno run --allow-all scripts/build-npm.ts <version> [--copy-readme]
import { build, emptyDir } from "@deno/dnt";

await emptyDir("./dist");

const packageVersion = Deno.args[0]?.replace(/^v/, "") ?? "0.0.0";

// --version needs this build's version; deno.json has it only for the
// Deno-native path, so generate the npm variant of src/cli/version.ts on
// every build (gitignored: it differs per release).
await Deno.writeTextFile(
  "./src/cli/version.node.ts",
  `// Auto-generated by scripts/build-npm.ts for this build only — not committed, do not edit.\nexport const PACKAGE_VERSION: string = ${
    JSON.stringify(packageVersion)
  };\n`,
);

// @pgfsm/db and @pgfsm/logging are published on their own: depend on them
// (at the version this build resolved) instead of inlining their source.
const range = async (denoJson: string) =>
  `^${JSON.parse(await Deno.readTextFile(denoJson)).version}`;
const dbVersionRange = await range("../fsm-core-db-ts/deno.json");
const loggingVersionRange = await range("../fsm-logging-ts/deno.json");

await build({
  entryPoints: [
    "./mod.ts",
    { kind: "bin", name: "pgfsm-api", path: "./src/cli/index.ts" },
  ],
  outDir: "./dist",
  // Tests stay out of the npm build (they need a database), as in the gateway.
  test: false,
  shims: {
    deno: true,
  },
  // The help text's invocation, --version and serving (Deno.serve vs
  // @hono/node-server) differ between this Deno source and the npm bin: swap
  // the modules (runtime detection doesn't work under dnt's Deno shim).
  mappings: {
    "./src/cli/invocation.ts": "./src/cli/invocation.node.ts",
    "./src/cli/version.ts": "./src/cli/version.node.ts",
    "./src/cli/serve.ts": "./src/cli/serve.node.ts",
    "@pgfsm/db": { name: "@pgfsm/db", version: dbVersionRange },
    "@pgfsm/logging": { name: "@pgfsm/logging", version: loggingVersionRange },
  },
  package: {
    name: "@pgfsm/api",
    version: packageVersion,
    description:
      "pgfsm REST API (pgfsm-api): FSM instances, definitions, API keys and the scheduler over HTTP, in front of fsm_core",
    license: "Apache-2.0",
    repository: {
      type: "git",
      url: "git+https://github.com/pgfsm/fsm.git",
      directory: "packages/fsm-api-ts",
    },
    // pg ships no types; dnt's type-check pass needs them (as in the gateway).
    devDependencies: {
      "@types/pg": "^8.18.0",
    },
  },
  compilerOptions: {
    lib: ["ES2022", "DOM"],
    target: "ES2022",
  },
  postBuild() {
    if (Deno.args.includes("--copy-readme")) {
      Deno.copyFileSync("README.md", "dist/README.md");
    }
  },
});
