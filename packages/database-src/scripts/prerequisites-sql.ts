// The prerequisites block that starts every plain-SQL install of fsm_core
// (SPEC-016): PostgreSQL 15+, fsm_core not installed yet, ltree, pg_cron and
// pgmq available (naming whatever's missing), then created. Its own module,
// with no top-level code; supabase-dump-for-full-version.ts uses
// withPrerequisites() to write the plain-SQL install.

export function prerequisites(version: string): string {
  return `-- ── Prerequisites ───────────────────────────────────────────────────────────
DO $preflight$
DECLARE
  missing text;
BEGIN
  IF current_setting('server_version_num')::int < 150000 THEN
    RAISE EXCEPTION 'fsm_core ${version} requires PostgreSQL 15 or later, found %',
      current_setting('server_version');
  END IF;
  IF EXISTS (SELECT 1 FROM pg_catalog.pg_namespace WHERE nspname = 'fsm_core') THEN
    RAISE EXCEPTION 'fsm_core is already installed: apply the upgrade scripts (fsm_core--<from>--<to>.sql) instead of the full install';
  END IF;
  SELECT string_agg(r.name, ', ' ORDER BY r.name) INTO missing
    FROM unnest(ARRAY['ltree', 'pg_cron', 'pgmq']) AS r(name)
   WHERE NOT EXISTS (SELECT 1 FROM pg_catalog.pg_available_extensions a WHERE a.name = r.name);
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'fsm_core requires the % extension(s), which this server doesn''t have', missing
      USING HINT = 'Install them on the server first (managed Postgres: enable them in the provider''s settings). pg_cron must also be in shared_preload_libraries, with cron.database_name set to this database.';
  END IF;
END;
$preflight$;

CREATE EXTENSION IF NOT EXISTS ltree;

DO $pg_cron$
BEGIN
  CREATE EXTENSION IF NOT EXISTS pg_cron;
EXCEPTION WHEN OTHERS THEN
  RAISE EXCEPTION 'fsm_core requires pg_cron: %', SQLERRM
    USING HINT = 'pg_cron must be in shared_preload_libraries, cron.database_name must name this database, and the installing login must be allowed to create it (on managed Postgres, the provider''s admin login).';
END;
$pg_cron$;

DO $pgmq$
BEGIN
  CREATE EXTENSION IF NOT EXISTS pgmq;
EXCEPTION WHEN OTHERS THEN
  RAISE EXCEPTION 'fsm_core requires pgmq: %', SQLERRM
    USING HINT = 'The installing login must be allowed to create it (on managed Postgres, the provider''s admin login).';
END;
$pgmq$;

CREATE SCHEMA IF NOT EXISTS fsm_core;
`;
}

/**
 * A full script turned into a plain-SQL install: a header, the
 * prerequisites block, then the script. An extension script's
 * `\echo … \quit` guard is dropped: psql would stop at it.
 */
/**
 * The licence header every generated fsm_core SQL artifact starts with
 * (SPEC-017): fsm_core is AGPL-3.0-only from 1.2.0, its first release (#710).
 */
export const SQL_LICENSE_HEADER =
  `-- SPDX-FileCopyrightText: 2025 Niraj Kashyap <niraj.38.re@gmail.com>
-- SPDX-License-Identifier: AGPL-3.0-only
-- fsm_core is free software under the GNU Affero General Public License v3.0
-- only; see https://github.com/pgfsm/fsm (LICENSE, REUSE.toml).
`;

export function withPrerequisites(
  version: string,
  fullScript: string,
  source: string,
): string {
  const body = fullScript
    .split("\n")
    .filter((line) => !/^\\echo .*\\quit\s*$/.test(line))
    .join("\n");
  // The full script starts with SQL_LICENSE_HEADER too; keep it once, first.
  const withoutHeader = body.startsWith(SQL_LICENSE_HEADER)
    ? body.slice(SQL_LICENSE_HEADER.length)
    : body;
  return [
    SQL_LICENSE_HEADER +
    `-- fsm_core ${version}: full install with prerequisite checks (SPEC-016).
-- Generated by packages/database-src/supabase-dump-for-full-version.ts from
-- ${source}; do not edit. Requires PostgreSQL 15+, ltree, pg_cron,
-- pgmq. Run as the database owner or the provider's admin login, in one
-- transaction: psql -1 -v ON_ERROR_STOP=1 -f <this file>
`,
    prerequisites(version),
    withoutHeader.trimEnd() + "\n",
  ].join("\n");
}
